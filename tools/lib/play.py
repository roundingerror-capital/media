SEAM_ORANGE = "#33120e"

def pal(**kw):
    """pal(RED="abcde", x="#hex") -> legend. A ramp name maps its 5 tones to the 5 chars ('.' skips a tone)."""
    out = {}
    for k, v in kw.items():
        if k in RAMPS:
            for ch, col in zip(v, RAMPS[k]):
                if ch != ".": out[ch] = col
        else: out[k] = v
    return out

