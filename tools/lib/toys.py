def rows_over(grid, rows, y0=0, x0=0):
    """Return a full grid with `rows` painted on from (x0, y0); '.' leaves the base, '_' erases to transparent."""
    g = [list(r) for r in grid]
    for j, r in enumerate(rows):
        for i, ch in enumerate(r):
            if ch == ".": continue
            g[y0 + j][x0 + i] = "." if ch == "_" else ch
    return ["".join(r) for r in g]


